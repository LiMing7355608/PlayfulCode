/* ------------------------------------------------------------------ *
 * 6. 模板渲染
 * ------------------------------------------------------------------ */

export interface ReviewPromptVars {
  target: string;
  extra?: string;
  /** 是否附上工具清单（文本协议模式下由协议模块负责，这里只做纯文本场景） */
  tools?: ToolSpec[];
}

export function buildReviewPrompt(vars: ReviewPromptVars): string {
  return REVIEW_TEMPLATE.replace('{TARGET}', vars.target).replace('{EXTRA}', vars.extra ? `\n**补充要求**：${vars.extra}\n` : '');
}

export function buildExplainPrompt(target: string, question: string): string {
  return EXPLAIN_TEMPLATE.replace('{TARGET}', target).replace('{QUESTION}', question);
}

export function buildTestPrompt(target: string): string {
  return TEST_TEMPLATE.replace('{TARGET}', target);
}

/** 渲染工具清单为人类可读文本（CLI --tools 展示用）。 */
export function renderToolList(tools: ToolSpec[]): string {
  return tools
    .map((t) => {
      const required = new Set(t.parameters.required ?? []);
      const params = Object.entries(t.parameters.properties ?? {})
        .map(([k, v]: [string, JsonSchema]) => `${k}${required.has(k) ? '' : '?'}:${v.type}`)
        .join(', ');
      return `- ${t.name}(${params})${t.dangerous ? ' ⚠️' : ''}\n    ${t.description}`;
    })
    .join('\n');
}
